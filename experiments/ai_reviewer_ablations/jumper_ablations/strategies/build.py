"""Turn the ablation configs into a strategies file the reviewer can read.

An ablation and a reviewer strategy are the same object - a flat
``id -> enabled`` map over context sources and prompt items - so the harness
does not reimplement any of it. It writes the presets in the reviewer's own
``strategies.yaml`` schema and points the reviewer at the file through
``JUMPER_AI_STRATEGIES_PATH``. From the pipeline's side an ablation is then
indistinguishable from a shipped strategy, which is the point: the experiment
measures the real code path, not a copy of it.
"""
from __future__ import annotations

import logging
from contextlib import contextmanager
from pathlib import Path
from typing import Iterator

import yaml
from hydra import compose, initialize_config_dir
from hydra.core.global_hydra import GlobalHydra

from jumper_ablations.config.schema import AblationConfig, load_ablation_config
from jumper_ablations.paths import CONFIGS_DIR, STRATEGIES_FILE

logger = logging.getLogger("jumper_ablations")

_ABLATION_GROUP = CONFIGS_DIR / "ablation"
_COMPOSE_ENTRY = "single_ablation"

_GENERATED_HEADER = """\
# GENERATED by `python -m jumper_ablations.cli.build_strategies` from
# configs/ablation/*.yaml. Do not edit: the next run overwrites it.
#
# The AI reviewer reads this file through JUMPER_AI_STRATEGIES_PATH and merges
# it over its own built-in strategies, so every id below is selectable as
# `%perfmonitor_ai_review --strategy <id>`.
"""


@contextmanager
def _hydra_context() -> Iterator[None]:
    """Compose against ``configs/`` whether or not Hydra already owns it.

    Called both from inside a ``@hydra.main`` entry point, where the search
    path is already set up, and from a bare script.
    """
    if GlobalHydra.instance().is_initialized():
        yield
        return
    with initialize_config_dir(version_base=None, config_dir=str(CONFIGS_DIR)):
        yield


def available_ablation_ids() -> list[str]:
    """Every option file in the ablation config group, sorted."""
    return sorted(path.stem for path in _ABLATION_GROUP.glob("*.yaml"))


def compose_ablation(ablation_id: str) -> AblationConfig:
    """Compose one ablation, honouring its ``defaults: [base]`` delta."""
    with _hydra_context():
        config = compose(
            config_name=_COMPOSE_ENTRY,
            overrides=[f"ablation={ablation_id}"],
        )
    ablation = load_ablation_config(config.ablation)
    if ablation.id != ablation_id:
        raise ValueError(
            f"configs/ablation/{ablation_id}.yaml declares id "
            f"'{ablation.id}'; the file name and the id must agree"
        )
    return ablation


def as_strategy_entry(ablation: AblationConfig) -> dict:
    """One ablation in the reviewer's ``strategies.yaml`` schema."""
    return {
        "id": ablation.id,
        "name": ablation.name,
        "description": ablation.description,
        "require_note": ablation.require_note,
        "effect": {
            "context": dict(ablation.effect.context),
            "overrides": dict(ablation.effect.overrides),
        },
    }


def build_strategies_file(
    ablation_ids: list[str] | None = None,
    destination: Path = STRATEGIES_FILE,
) -> Path:
    """Write every ablation to *destination* and return the path.

    Writing all of them rather than only the ones a suite uses keeps the file
    stable across runs, so ``--strategy`` completion and a hand inspection of
    the presets do not depend on which suite ran last.
    """
    ids = ablation_ids if ablation_ids is not None else available_ablation_ids()
    entries = [as_strategy_entry(compose_ablation(one)) for one in ids]

    destination.parent.mkdir(parents=True, exist_ok=True)
    body = yaml.safe_dump(
        {"strategies": entries},
        sort_keys=False,
        default_flow_style=False,
        allow_unicode=True,
    )
    destination.write_text(_GENERATED_HEADER + "\n" + body, encoding="utf-8")
    logger.info(f"wrote {len(entries)} strategies to {destination}")
    return destination
